<?php
/**
 * Regenerates the two icon-picker assets from Icon_Library::GLYPHS:
 *
 *   assets/icons/sz-icons.json         the list Elementor's picker fetches
 *   assets/icons/sz-icons-picker.css   picker previews (editor only)
 *
 * The PHP map is the single source of truth; these two files are derived.
 * Run after adding or changing a glyph:
 *
 *   php tools/build-icons.php
 *
 * tests/run.php fails if the committed files drift from the map.
 */

if ( PHP_SAPI !== 'cli' ) {
	exit( 1 );
}

define( 'ABSPATH', __DIR__ . '/' ); // satisfies the class file's direct-access guard; nothing else is loaded

require dirname( __DIR__ ) . '/includes/Icon_Library.php';

use Samanzavarian_Widgets\Icon_Library;

/** @return array{json:string,css:string} */
function szw_build_icon_assets(): array {
	$names = array_keys( Icon_Library::GLYPHS );

	$json = json_encode( [ 'icons' => $names ], JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES ) . "\n";

	$css  = "/* Generated by tools/build-icons.php from Icon_Library::GLYPHS — do not edit by hand.\n";
	$css .= "   Loaded only in the Elementor editor, to draw previews in the icon picker. The frontend\n";
	$css .= "   renders these glyphs as inline SVG and never downloads this file. */\n";

	// `i.szi` and never `.szi`: the frontend's inline <svg> carries the same
	// classes, and must not get a mask painted on top of it.
	$css .= 'i.szi{display:inline-block;width:1em;height:1em;vertical-align:-.125em;background-color:currentColor;'
		. '-webkit-mask:var(--szi) center/contain no-repeat;mask:var(--szi) center/contain no-repeat}' . "\n";

	foreach ( Icon_Library::GLYPHS as $name => $inner ) {
		$svg = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="#000" stroke-width="2" '
			. 'stroke-linecap="round" stroke-linejoin="round">' . $inner . '</svg>';

		// Minimal, valid encoding for a CSS url(): quotes become single, and
		// the four characters that break a data URI are percent-encoded.
		$uri = str_replace( [ '"', '%', '#', '<', '>' ], [ "'", '%25', '%23', '%3C', '%3E' ], $svg );

		$css .= 'i.szi-' . $name . '{--szi:url("data:image/svg+xml,' . $uri . '")}' . "\n";
	}

	return [ 'json' => $json, 'css' => $css ];
}

$root   = dirname( __DIR__ );
$assets = szw_build_icon_assets();

if ( in_array( '--check', $argv, true ) ) {
	$ok = file_get_contents( $root . '/assets/icons/sz-icons.json' ) === $assets['json']
		&& file_get_contents( $root . '/assets/icons/sz-icons-picker.css' ) === $assets['css'];

	fwrite( STDOUT, $ok ? "icon assets in sync\n" : "icon assets OUT OF SYNC — run: php tools/build-icons.php\n" );
	exit( $ok ? 0 : 1 );
}

if ( ! is_dir( $root . '/assets/icons' ) ) {
	mkdir( $root . '/assets/icons', 0755, true );
}

file_put_contents( $root . '/assets/icons/sz-icons.json', $assets['json'] );
file_put_contents( $root . '/assets/icons/sz-icons-picker.css', $assets['css'] );

fwrite( STDOUT, sprintf( "wrote %d icons\n", count( Icon_Library::GLYPHS ) ) );
